let generatedData = {};

async function generatePlan() {
    const name = document.getElementById("name").value.trim();
    const age = Number(document.getElementById("age").value);
    const height = Number(document.getElementById("height").value);
    const weight = Number(document.getElementById("weight").value);
    const level = document.getElementById("level").value;
    const goal = document.getElementById("goal").value;

    if (!name || !age || !height || !weight || !level || !goal) {
        alert("Please fill all the details.");
        return;
    }

    if (age < 10 || age > 100) {
        alert("Please enter a valid age.");
        return;
    }

    if (height <= 0 || weight <= 0) {
        alert("Please enter valid height and weight.");
        return;
    }

    const heightMeter = height / 100;
    const bmi = weight / (heightMeter * heightMeter);

    let bmiStatus;

    if (bmi < 18.5) bmiStatus = "Underweight";
    else if (bmi < 25) bmiStatus = "Normal";
    else if (bmi < 30) bmiStatus = "Overweight";
    else bmiStatus = "Obesity range";

    generatedData = {
        name, age, height, weight, level, goal,
        bmi: bmi.toFixed(1),
        bmiStatus
    };

    document.getElementById("userInfo").innerHTML = `
        <div class="user-info">
            <strong>Name:</strong> ${name}<br>
            <strong>Age:</strong> ${age} years<br>
            <strong>Height:</strong> ${height} cm<br>
            <strong>Weight:</strong> ${weight} kg<br>
            <strong>Fitness Level:</strong> ${level}<br>
            <strong>Fitness Goal:</strong> ${goal}
        </div>
    `;

    document.getElementById("bmiBox").innerHTML = `
        <div class="bmi">
            <strong>BMI:</strong> ${bmi.toFixed(1)}<br>
            <strong>Status:</strong> ${bmiStatus}
        </div>
    `;

    document.getElementById("loading").style.display = "block";
    document.getElementById("result").style.display = "none";

    try {
        const response = await fetch("/api/generate-plan", {
            method: "POST",
            headers: {
                "Content-Type": "application/json"
            },
            body: JSON.stringify({
                name,
                age,
                height,
                weight,
                level,
                goal,
                bmi: bmi.toFixed(1),
                bmiStatus
            })
        });

        const data = await response.json();

        if (!response.ok) {
            throw new Error(data.error || "Failed to generate plan.");
        }

        document.getElementById("aiPlan").innerHTML = data.plan;
        document.getElementById("result").style.display = "block";

    } catch (error) {
        console.error(error);
        alert(error.message);
    }

    document.getElementById("loading").style.display = "none";

    document.getElementById("result").scrollIntoView({
        behavior: "smooth"
    });
}

function downloadPDF() {
    if (!window.jspdf) {
        alert("jsPDF library not found.");
        return;
    }

    const { jsPDF } = window.jspdf;
    const doc = new jsPDF();

    let y = 20;

    doc.setFontSize(20);
    doc.text("FitBuddy", 20, y);

    y += 9;
    doc.setFontSize(12);
    doc.text("AI Fitness Plan Generator", 20, y);

    y += 15;
    doc.setFontSize(10);

    [
        `Name: ${generatedData.name}`,
        `Age: ${generatedData.age}`,
        `Height: ${generatedData.height} cm`,
        `Weight: ${generatedData.weight} kg`,
        `Fitness Level: ${generatedData.level}`,
        `Fitness Goal: ${generatedData.goal}`,
        `BMI: ${generatedData.bmi} (${generatedData.bmiStatus})`
    ].forEach(line => {
        doc.text(line, 20, y);
        y += 7;
    });

    y += 8;
    doc.setFontSize(14);
    doc.text("AI Generated Fitness Plan", 20, y);

    y += 10;
    doc.setFontSize(9);

    const plan = document.getElementById("aiPlan").innerText;
    const lines = doc.splitTextToSize(plan, 170);

    lines.forEach(line => {
        if (y > 275) {
            doc.addPage();
            y = 20;
        }

        doc.text(line, 20, y);
        y += 5;
    });

    if (y > 270) {
        doc.addPage();
        y = 20;
    }

    y += 8;
    doc.setFontSize(8);
    doc.text("Generated by FitBuddy using Gemini AI.", 20, y);

    doc.save(`${generatedData.name}-FitBuddy-Plan.pdf`);
}
